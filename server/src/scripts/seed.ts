/**
 * Idempotent curriculum and demo-data seeder.
 *
 * Usage:
 *   npm run seed              # seed curriculum, admin, demo user and demo progress
 *   npm run seed -- --no-demo # seed curriculum and admin only
 *
 * The seeder upserts by stable keys, so running it repeatedly is safe:
 *   - roadmaps  -> slug
 *   - modules   -> (roadmapId, key)
 *   - topics    -> (roadmapId, key)
 *   - tasks     -> (roadmapId, key)
 *
 * Existing documents keep their `_id`, which is what preserves user progress
 * (TaskProgress references task ids) across curriculum updates. Seeded items
 * that disappear from the curriculum are archived, never deleted.
 */
