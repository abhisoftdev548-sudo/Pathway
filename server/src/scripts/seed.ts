const SEED_VERSION = 1;
const BATCH_SIZE = 400;
const DAY_MS = 24 * 60 * 60 * 1000;
const DEMO_TIME_ZONE = 'Asia/Kolkata';

/** Keys generated by the curriculum builder; only these are eligible for stale archival. */
const SEEDED_TASK_KEY = /^m\d+-t\d+-(learn|practice|apply|quiz)$/;
const SEEDED_TOPIC_KEY = /^m\d+-t\d+$/;
const SEEDED_MODULE_KEY = /^m\d+$/;

type UpdateOperation = {
  updateOne: {
    filter: Record<string, unknown>;
    update: Record<string, unknown>;
    upsert: boolean;
  };
};

interface BulkWritable {
  bulkWrite(operations: never, options?: { ordered?: boolean }): Promise<unknown>;
}

async function runBulk(model: BulkWritable, operations: UpdateOperation[]): Promise<number> {
  for (let index = 0; index < operations.length; index += BATCH_SIZE) {
    const batch = operations.slice(index, index + BATCH_SIZE);
    await model.bulkWrite(batch as never, { ordered: false });
  }
  return operations.length;
}

interface SeededRoadmap {
  roadmap: RoadmapDocument;
  tasks: TaskDocument[];
}

async function seedCurriculum(force: boolean): Promise<Map<string, SeededRoadmap>> {
  const result = new Map<string, SeededRoadmap>();
  let moduleCount = 0;
  let topicCount = 0;
  let taskCount = 0;

  for (const seed of seedRoadmaps) {
    const roadmap = await upsertRoadmap(seed);

    // ── Modules ────────────────────────────────────────────────────────────
    const moduleOps: UpdateOperation[] = seed.modules.map((module) => {
      const content = {
        title: module.title,
        description: module.description,
        order: module.order,
        learningOutcomes: module.learningOutcomes,
        published: module.published,
        archivedAt: null,
      };
      return {
        updateOne: {
          filter: { roadmapId: roadmap._id, key: module.key },
          update: force
            ? { $set: content, $setOnInsert: { roadmapId: roadmap._id, key: module.key } }
            : { $setOnInsert: { roadmapId: roadmap._id, key: module.key, ...content } },
          upsert: true,
        },
      };
    });
    await runBulk(ModuleModel, moduleOps);

    const modules = await ModuleModel.find({ roadmapId: roadmap._id }).select('_id key');
    const moduleIdByKey = new Map(modules.map((module) => [module.key, module._id]));

    await runBulk(
      ModuleModel,
      seed.modules.map((module) => {
        const prerequisiteIds = module.prerequisiteKeys
          .map((key) => moduleIdByKey.get(key))
          .filter((id): id is mongoose.Types.ObjectId => Boolean(id));
        return {
          updateOne: {
            filter: { roadmapId: roadmap._id, key: module.key },
            update: { $set: { prerequisiteModuleIds: prerequisiteIds } },
            upsert: false,
          },
        };
      }),
    );

    // ── Topics ─────────────────────────────────────────────────────────────
    const topicOps: UpdateOperation[] = [];
    for (const module of seed.modules) {
      const moduleId = moduleIdByKey.get(module.key);
      if (!moduleId) continue;
      for (const topic of module.topics) {
        const content = {
          moduleId,
          title: topic.title,
          description: topic.description,
          order: topic.order,
          estimatedDuration: topic.estimatedDuration,
          learningOutcomes: topic.learningOutcomes,
          resources: topic.resources,
          published: topic.published,
          archivedAt: null,
        };
        topicOps.push({
          updateOne: {
            filter: { roadmapId: roadmap._id, key: topic.key },
            update: force
              ? { $set: content, $setOnInsert: { roadmapId: roadmap._id, key: topic.key } }
              : { $setOnInsert: { roadmapId: roadmap._id, key: topic.key, ...content } },
            upsert: true,
          },
        });
      }
    }
    await runBulk(Topic, topicOps);

    const topics = await Topic.find({ roadmapId: roadmap._id }).select('_id key');
    const topicIdByKey = new Map(topics.map((topic) => [topic.key, topic._id]));

    const topicPrereqOps: UpdateOperation[] = [];
    for (const module of seed.modules) {
      for (const topic of module.topics) {
        const prerequisiteIds = topic.prerequisiteKeys
          .map((key) => topicIdByKey.get(key))
          .filter((id): id is mongoose.Types.ObjectId => Boolean(id));
        topicPrereqOps.push({
          updateOne: {
            filter: { roadmapId: roadmap._id, key: topic.key },
            update: { $set: { prerequisites: prerequisiteIds } },
            upsert: false,
          },
        });
      }
    }
    await runBulk(Topic, topicPrereqOps);

    // ── Tasks ──────────────────────────────────────────────────────────────
    const taskOps: UpdateOperation[] = [];
    for (const module of seed.modules) {
      const moduleId = moduleIdByKey.get(module.key);
      if (!moduleId) continue;
      for (const topic of module.topics) {
        const topicId = topicIdByKey.get(topic.key);
        if (!topicId) continue;
        for (const task of topic.tasks) {
          const content = {
            moduleId,
            topicId,
            title: task.title,
            description: task.description,
            type: task.type,
            difficulty: task.difficulty,
            estimatedDuration: task.estimatedDuration,
            learningObjectives: task.learningObjectives,
            instructions: task.instructions,
            acceptanceCriteria: task.acceptanceCriteria,
            resources: task.resources,
            quizQuestions: task.quizQuestions,
            codingExercise: task.codingExercise,
            published: task.published,
            order: task.order,
            archivedAt: null,
          };
          taskOps.push({
            updateOne: {
              filter: { roadmapId: roadmap._id, key: task.key },
              update: force
                ? { $set: content, $setOnInsert: { roadmapId: roadmap._id, key: task.key } }
                : { $setOnInsert: { roadmapId: roadmap._id, key: task.key, ...content } },
              upsert: true,
            },
          });
        }
      }
    }
    await runBulk(Task, taskOps);

    const tasks = await Task.find({ roadmapId: roadmap._id }).select('_id key');
    const taskIdByKey = new Map(tasks.map((task) => [task.key, task._id]));

    const taskPrereqOps: UpdateOperation[] = [];
    for (const module of seed.modules) {
      for (const topic of module.topics) {
        for (const task of topic.tasks) {
          const prerequisiteIds = task.prerequisiteKeys
            .map((key) => taskIdByKey.get(key))
            .filter((id): id is mongoose.Types.ObjectId => Boolean(id));
          taskPrereqOps.push({
            updateOne: {
              filter: { roadmapId: roadmap._id, key: task.key },
              update: { $set: { prerequisites: prerequisiteIds } },
              upsert: false,
            },
          });
        }
      }
    }
    await runBulk(Task, taskPrereqOps);

    await archiveStaleContent(roadmap._id, seed);

    // Return tasks in curriculum order (module order, topic order, task order).
    const seedTaskOrder = new Map<string, number>();
    let position = 0;
    for (const module of seed.modules) {
      for (const topic of module.topics) {
        for (const task of topic.tasks) {
          seedTaskOrder.set(task.key, position++);
        }
      }
    }
    const orderedTasks = await Task.find({
      roadmapId: roadmap._id,
      published: true,
      archivedAt: null,
    });
    orderedTasks.sort(
      (a, b) => (seedTaskOrder.get(a.key) ?? Number.MAX_SAFE_INTEGER) - (seedTaskOrder.get(b.key) ?? Number.MAX_SAFE_INTEGER),
    );

    result.set(seed.slug, { roadmap, tasks: orderedTasks });
    moduleCount += seed.modules.length;
    topicCount += seed.modules.reduce((sum, module) => sum + module.topics.length, 0);
    taskCount += seedTaskOrder.size;
    logger.info(
      { slug: seed.slug, modules: seed.modules.length, tasks: seedTaskOrder.size },
      'Seeded roadmap',
    );
  }

  logger.info({ roadmaps: seedRoadmaps.length, modules: moduleCount, topics: topicCount, tasks: taskCount }, 'Curriculum seed complete');
  return result;
}

async function upsertRoadmap(seed: SeedRoadmap): Promise<RoadmapDocument> {
  const roadmap = await Roadmap.findOneAndUpdate(
    { slug: seed.slug },
    {
      $set: {
        title: seed.title,
        tagline: seed.tagline,
        description: seed.description,
        category: seed.category,
        difficulty: seed.difficulty,
        difficultyLabel: seed.difficultyLabel,
        estimatedDuration: seed.estimatedDuration,
        prerequisites: seed.prerequisites,
        learningOutcomes: seed.learningOutcomes,
        skills: seed.skills,
        tags: seed.tags,
        icon: seed.icon,
        published: true,
        archivedAt: null,
        seedVersion: SEED_VERSION,
      },
      $setOnInsert: { slug: seed.slug, version: 1, publishedAt: null },
    },
    { upsert: true, new: true, setDefaultsOnInsert: true },
  );
  if (!roadmap) throw new Error(`Failed to upsert roadmap ${seed.slug}`);
  if (!roadmap.publishedAt) {
    roadmap.publishedAt = new Date();
    await roadmap.save();
  }
  return roadmap;
}

async function archiveStaleContent(roadmapId: mongoose.Types.ObjectId, seed: SeedRoadmap): Promise<void> {
  const now = new Date();
  const [existingModules, existingTopics, existingTasks] = await Promise.all([
    ModuleModel.find({ roadmapId, archivedAt: null }).select('key'),
    Topic.find({ roadmapId, archivedAt: null }).select('key'),
    Task.find({ roadmapId, archivedAt: null }).select('key'),
  ]);

  const seedModuleKeys = new Set(seed.modules.map((module) => module.key));
  const seedTopicKeys = new Set<string>();
  const seedTaskKeys = new Set<string>();
  for (const module of seed.modules) {
    for (const topic of module.topics) {
      seedTopicKeys.add(topic.key);
      for (const task of topic.tasks) seedTaskKeys.add(task.key);
    }
  }

  const staleModules = existingModules
    .map((module) => module.key)
    .filter((key) => SEEDED_MODULE_KEY.test(key) && !seedModuleKeys.has(key));
  const staleTopics = existingTopics
    .map((topic) => topic.key)
    .filter((key) => SEEDED_TOPIC_KEY.test(key) && !seedTopicKeys.has(key));
  const staleTasks = existingTasks
    .map((task) => task.key)
    .filter((key) => SEEDED_TASK_KEY.test(key) && !seedTaskKeys.has(key));

  if (staleModules.length > 0) {
    await ModuleModel.updateMany(
      { roadmapId, key: { $in: staleModules } },
      { $set: { archivedAt: now, published: false } },
    );
  }
  if (staleTopics.length > 0) {
    await Topic.updateMany(
      { roadmapId, key: { $in: staleTopics } },
      { $set: { archivedAt: now, published: false } },
    );
  }
  if (staleTasks.length > 0) {
    await Task.updateMany(
      { roadmapId, key: { $in: staleTasks } },
      { $set: { archivedAt: now, published: false } },
    );
  }

  if (staleModules.length + staleTopics.length + staleTasks.length > 0) {
    logger.warn(
      { roadmap: seed.slug, modules: staleModules.length, topics: staleTopics.length, tasks: staleTasks.length },
      'Archived curriculum items no longer present in the seed',
    );
  }
}

async function upsertUser(input: {
  name: string;
  email: string;
  password: string;
  role: 'admin' | 'user';
  timeZone: string;
  dailyGoalMinutes: number;
}) {
  const email = input.email.toLowerCase();
  const existing = await User.findOne({ email });
  if (existing) {
    const updates: Record<string, unknown> = {};
    if (existing.role !== input.role) updates.role = input.role;
    if (!existing.name) updates.name = input.name;
    if (!existing.isActive) updates.isActive = true;
    if (Object.keys(updates).length > 0) {
      await User.updateOne({ _id: existing._id }, { $set: updates });
    }
    logger.info({ email, role: input.role, created: false }, 'Seed user exists');
    return { user: existing, created: false };
  }

  const user = await User.create({
    name: input.name,
    email,
    passwordHash: await hashPassword(input.password),
    role: input.role,
    timezone: input.timeZone,
    dailyGoalMinutes: input.dailyGoalMinutes,
  });
  logger.info({ email, role: input.role, created: true }, 'Seed user created');
  return { user, created: true };
}

async function seedDemoProgress(demoUserId: mongoose.Types.ObjectId, curriculum: Map<string, SeededRoadmap>) {
  const existingCompleted = await TaskProgress.countDocuments({ userId: demoUserId, status: 'completed' });
  if (existingCompleted > 0) {
    logger.info({ completed: existingCompleted }, 'Demo progress already present; skipping progress seed');
    return;
  }

  const plan: {
    slug: string;
    pace: 'relaxed' | 'standard' | 'intensive';
    daysAgo: number;
    completed: number;
    inProgress: number;
    /** Push this roadmap's completions further into the past. */
    shiftDays: number;
  }[] = [
    { slug: 'programming-fundamentals', pace: 'standard', daysAgo: 18, completed: 16, inProgress: 2, shiftDays: 0 },
    { slug: 'computer-fundamentals', pace: 'relaxed', daysAgo: 9, completed: 6, inProgress: 1, shiftDays: 0 },
    { slug: 'problem-solving-and-algorithms', pace: 'intensive', daysAgo: 25, completed: 3, inProgress: 0, shiftDays: 7 },
  ];

  const now = Date.now();
  const activity: Parameters<typeof recordActivity>[0][] = [];

  for (const entry of plan) {
    const seeded = curriculum.get(entry.slug);
    if (!seeded) continue;
    const { roadmap, tasks } = seeded;

    const enrollment = await Enrollment.findOneAndUpdate(
      { userId: demoUserId, roadmapId: roadmap._id },
      {
        $setOnInsert: {
          userId: demoUserId,
          roadmapId: roadmap._id,
          curriculumVersion: roadmap.version,
          status: entry.slug === 'problem-solving-and-algorithms' ? 'paused' : 'active',
          enrolledAt: new Date(now - (entry.daysAgo + 2) * DAY_MS),
          startedAt: new Date(now - entry.daysAgo * DAY_MS),
          pausedAt: entry.slug === 'problem-solving-and-algorithms' ? new Date(now - 5 * DAY_MS) : null,
          learningPace: entry.pace,
          lastActivityAt: new Date(now - DAY_MS),
        },
      },
      { upsert: true, new: true, setDefaultsOnInsert: true },
    );
    if (!enrollment) continue;

    // Materialise not_started rows first, exactly like a real enrollment does.
    await ensureProgressRecords(String(demoUserId), enrollment, tasks);

    const selected = tasks.slice(0, entry.completed + entry.inProgress);
    const progressOps: UpdateOperation[] = [];
    const completedIds: mongoose.Types.ObjectId[] = [];
    let earliestCompletion: Date | null = null;

    selected.forEach((task, index) => {
      if (index < entry.completed) {
        // Spread completions across consecutive recent days, ending yesterday.
        const dayOffset = Math.max(1, Math.ceil((entry.completed - index) / 2)) + entry.shiftDays;
        const timestamp = new Date(now - dayOffset * DAY_MS);
        const actualDuration = Math.max(5, task.estimatedDuration + (index % 3) * 5 - 5);
        progressOps.push({
          updateOne: {
            filter: { userId: demoUserId, taskId: task._id },
            update: {
              $set: {
                status: 'completed',
                completedAt: timestamp,
                firstCompletedAt: timestamp,
                actualDuration,
                lastInteractionAt: timestamp,
                attemptCount: 1,
                selfVerified: true,
              },
            },
            upsert: false,
          },
        });
        completedIds.push(task._id);
        if (!earliestCompletion || timestamp < earliestCompletion) earliestCompletion = timestamp;
        activity.push({
          userId: demoUserId,
          activityType: 'task_completed',
          timeZone: DEMO_TIME_ZONE,
          enrollmentId: enrollment._id,
          roadmapId: roadmap._id,
          taskId: task._id,
          minutes: actualDuration,
          timestamp,
          metadata: { seeded: true },
        });
      } else {
        progressOps.push({
          updateOne: {
            filter: { userId: demoUserId, taskId: task._id },
            update: { $set: { status: 'in_progress', lastInteractionAt: new Date(now - DAY_MS) } },
            upsert: false,
          },
        });
      }
    });

    await runBulk(TaskProgress, progressOps);

    activity.push({
      userId: demoUserId,
      activityType: 'enrollment_created',
      timeZone: DEMO_TIME_ZONE,
      enrollmentId: enrollment._id,
      roadmapId: roadmap._id,
      timestamp: new Date(now - (entry.daysAgo + 2) * DAY_MS),
      metadata: { seeded: true, pace: entry.pace },
    });

    // Keep enrollment state consistent with the seeded progress.
    await Enrollment.updateOne(
      { _id: enrollment._id },
      {
        $set: {
          startedAt: earliestCompletion ?? enrollment.startedAt,
          lastActivityAt: new Date(now - DAY_MS),
          curriculumVersion: roadmap.version,
        },
      },
    );

    logger.info({ slug: entry.slug, completed: entry.completed, inProgress: entry.inProgress }, 'Seeded demo enrollment');
  }

  for (const entry of activity) await recordActivity(entry);
  await rebuildDailyActivity(String(demoUserId), DEMO_TIME_ZONE, 45);
  await evaluateAchievements(String(demoUserId), DEMO_TIME_ZONE);
}

async function main() {
  const includeDemo = !process.argv.includes('--no-demo');
  const force = process.argv.includes('--force');
  logger.info({ env: env.nodeEnv, force }, 'Starting PathForge seed');

  await connectDatabase();

  const curriculum = await seedCurriculum(force);

  await upsertUser({
    name: env.seedAdmin.name,
    email: env.seedAdmin.email,
    password: env.seedAdmin.password,
    role: 'admin',
    timeZone: 'UTC',
    dailyGoalMinutes: 45,
  });

  if (includeDemo) {
    const { user } = await upsertUser({
      name: env.seedDemo.name,
      email: env.seedDemo.email,
      password: env.seedDemo.password,
      role: 'user',
      timeZone: DEMO_TIME_ZONE,
      dailyGoalMinutes: 45,
    });
    await seedDemoProgress(user._id, curriculum);
  }

  const activityEvents = await ActivityLog.countDocuments({});
  logger.info(
    {
      roadmaps: seedRoadmaps.length,
      activityEvents,
      demoToday: todayString(DEMO_TIME_ZONE),
    },
    'Seed finished',
  );
  await disconnectDatabase();
}

main().catch(async (error) => {
  logger.error({ err: error }, 'Seed failed');
  await disconnectDatabase().catch(() => undefined);
  process.exit(1);
});
